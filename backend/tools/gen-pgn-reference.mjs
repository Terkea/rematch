#!/usr/bin/env node
// Regenerates backend/fixtures/pgn/realworld-reference.json.
//
// Provenance: expected values come from the TS reference `parsePgn`
// (packages/chess-core, chess.js 1.4.0), run over
//   - apps/worker/test/fixtures/lichess-games.ndjson   (recorded Lichess exports)
//   - apps/worker/test/fixtures/chesscom-month.json    (recorded chess.com month)
//   - backend/fixtures/pgn/terminal/*.pgn              (hand-written legal games:
//     checkmate, stalemate, threefold repetition)
// Games the TS parser rejects (Chess960 etc.) are skipped. The Rust test
// tests/pgn.rs asserts SAN/UCI/FEN/clock/terminal parity with this file.
//
// Usage (from anywhere): node backend/tools/gen-pgn-reference.mjs
// Needs a built packages/chess-core (dist/) with node_modules, i.e. the main
// checkout. Override with TS_ROOT=<repo root>. Output is deterministic.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const backend = resolve(here, "..");
const wt = here.indexOf(`${join("", ".worktrees")}`);
const tsRoot = process.env.TS_ROOT ?? (wt > 0 ? here.slice(0, wt - 1) : resolve(backend, ".."));
const { parsePgn } = await import(
  pathToFileURL(join(tsRoot, "packages/chess-core/dist/index.js")).href
);
const fixtures = join(tsRoot, "apps/worker/test/fixtures");

const inputs = [];
for (const line of readFileSync(join(fixtures, "lichess-games.ndjson"), "utf8").split("\n")) {
  if (line.trim() === "") continue;
  const g = JSON.parse(line);
  if (g.variant !== "standard") continue; // Chess960 PGNs carry no Variant tag
  inputs.push({ name: `lichess-${g.id}`, pgn: g.pgn, daily: false });
}
const month = JSON.parse(readFileSync(join(fixtures, "chesscom-month.json"), "utf8"));
month.games.forEach((g, i) => {
  if (g.rules !== "chess") return;
  inputs.push({ name: `chesscom-${i}-${g.time_class}`, pgn: g.pgn, daily: g.time_class === "daily" });
});
const termDir = join(backend, "fixtures/pgn/terminal");
for (const f of readdirSync(termDir).filter((f) => f.endsWith(".pgn")).sort()) {
  inputs.push({ name: `terminal-${f.replace(/\.pgn$/, "")}`, pgn: readFileSync(join(termDir, f), "utf8"), daily: false, noClocks: true });
}

const cases = [];
for (const { name, pgn, daily, noClocks } of inputs) {
  let g;
  try {
    g = parsePgn(pgn);
  } catch (e) {
    if (e?.name === "UnsupportedVariantError") continue;
    throw new Error(`${name}: ${e}`);
  }
  cases.push({
    name,
    pgn,
    daily,
    noClocks: noClocks === true,
    terminal: g.terminal,
    plies: g.plies.map((p) => [p.san, p.uci, p.fenBefore, p.fenAfter, p.clockSeconds]),
  });
}
const provenance =
  "Generated by backend/tools/gen-pgn-reference.mjs from the TS parsePgn (chess.js 1.4.0); do not edit by hand.";
writeFileSync(join(backend, "fixtures/pgn/realworld-reference.json"), JSON.stringify({ provenance, cases }));
console.log(`wrote ${cases.length} cases`);
