// Regenerates src/board/pieces.generated.ts from the committed Commons SVGs in
// assets/pieces/cburnett/ (run `pnpm --filter @ci/ui pieces`). board.test.tsx fails if the two drift.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildPieces, PIECE_FILES } from "./build-pieces-lib.js";

const dir = new URL("../assets/pieces/cburnett/", import.meta.url);
const out = fileURLToPath(new URL("../src/board/pieces.generated.ts", import.meta.url));

const sources = Object.fromEntries(
  PIECE_FILES.map(({ file }) => [file, readFileSync(new URL(file, dir), "utf8")]),
);

writeFileSync(
  out,
  `// Generated by scripts/build-pieces.ts from assets/pieces/cburnett/ (Colin M.L. Burnett,
// Wikimedia Commons, BSD-3-Clause; see that directory's LICENSE). Do not edit by hand.
import type { PieceSet } from "./piece-types.js";

export const cburnett: PieceSet = ${JSON.stringify(buildPieces(sources), null, 2)};
`,
);
execFileSync("pnpm", ["exec", "biome", "format", "--write", out], {
  stdio: "inherit",
  shell: true,
});
console.log(out);
