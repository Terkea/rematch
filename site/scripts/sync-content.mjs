#!/usr/bin/env node
// Build-time content for the site (run before `astro dev`, `astro build` and `astro sync`):
// - the design tokens, from packages/ui/src/styles/tokens.css (DESIGN.md is the law), turned from a
//   Tailwind @theme block into plain custom properties;
// - the decision log, one page per docs/decisions/*.md plus an index from its README;
// - the research notes, one page per docs/research/*.md plus an index.
// Everything written here is git-ignored and regenerated on every build.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BASE, GITHUB_BLOB, rewriteMarkdown, slugOf, titleOf } from "./content-lib.mjs";

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(SITE, "..");
const OUT_DOCS = join(SITE, "src", "content", "docs", "docs");

// ---- tokens ---------------------------------------------------------------
export function tokensToPlainCss(css) {
  return (
    "/* Generated by site/scripts/sync-content.mjs from packages/ui/src/styles/tokens.css. Do not edit. */\n" +
    css
      .replace(/^@custom-variant[^\n]*\n/m, "")
      .replace(/@theme static \{/, ":root {")
      .replace(/^\s*--[a-z-]+-\*: initial;\n/gm, "")
  );
}

function writeTokens() {
  const src = readFileSync(join(ROOT, "packages", "ui", "src", "styles", "tokens.css"), "utf8");
  const dir = join(SITE, "src", "styles", "generated");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "tokens.css"), tokensToPlainCss(src));
}

// ---- markdown collections ---------------------------------------------------
function frontmatter(fields) {
  const lines = Object.entries(fields)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `${k}: ${typeof v === "string" ? JSON.stringify(v) : JSON.stringify(v)}`);
  return `---\n${lines.join("\n")}\n---\n\n`;
}

/** Collects `docs/<dir>/*.md` into `<out>/<slug>.md`; the README (if any) becomes the index. */
function syncCollection({ dir, route, indexTitle, indexIntro, order }) {
  const srcDir = join(ROOT, "docs", dir);
  const outDir = join(OUT_DOCS, route);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const files = readdirSync(srcDir)
    .filter((f) => f.endsWith(".md"))
    .sort();
  const pages = [];
  for (const file of files) {
    const raw = readFileSync(join(srcDir, file), "utf8");
    const repoPath = posix.join("docs", dir, file);
    const body = rewriteMarkdown(raw, repoPath);
    if (file === "README.md") continue;
    const title = titleOf(raw) ?? file.replace(/\.md$/, "");
    const slug = slugOf(file);
    pages.push({ file, slug, title });
    const withoutH1 = body.replace(/^# [^\n]*\n+/, "");
    writeFileSync(
      join(outDir, `${slug}.md`),
      frontmatter({
        title,
        editUrl: `${GITHUB_BLOB.replace("/blob/", "/edit/")}/${repoPath}`,
        sidebar: order ? { order: order(file) } : undefined,
      }) +
        `> Source: [\`${repoPath}\`](${GITHUB_BLOB}/${repoPath}). Generated at build time; edit the source file.\n\n` +
        withoutH1,
    );
  }
  let index;
  const readme = files.includes("README.md")
    ? readFileSync(join(srcDir, "README.md"), "utf8")
    : null;
  if (readme) {
    index = rewriteMarkdown(readme, posix.join("docs", dir, "README.md")).replace(
      /^# [^\n]*\n+/,
      "",
    );
  } else {
    index = pages.map((p) => `- [${p.title}](${BASE}/docs/${route}/${p.slug}/)`).join("\n");
  }
  writeFileSync(
    join(outDir, "index.md"),
    frontmatter({ title: indexTitle, sidebar: { order: 0, label: "Index" } }) +
      `${indexIntro}\n\n${index}\n`,
  );
  return pages;
}

export function sync() {
  writeTokens();
  const decisions = syncCollection({
    dir: "decisions",
    route: "decisions",
    indexTitle: "Decision log",
    indexIntro:
      "Every decision in Rematch is written down as an architecture decision record (ADR): the context, the decision, the alternatives and the consequences. This log is generated at build time from [`docs/decisions/`](" +
      GITHUB_BLOB.replace("/blob/", "/tree/") +
      "/docs/decisions), so it is always the repository's own record. New decisions take the next number.",
    order: (f) => {
      const n = /^(\d{4})/.exec(f);
      return n ? Number(n[1]) : 10000;
    },
  });
  const research = syncCollection({
    dir: "research",
    route: "research",
    indexTitle: "Research notes",
    indexIntro:
      "The evidence behind the product: what helps amateur players improve, how competitors work, the legal ground and the technical facts the engine relies on. Generated at build time from [`docs/research/`](" +
      GITHUB_BLOB.replace("/blob/", "/tree/") +
      "/docs/research).",
  });
  return { decisions: decisions.length, research: research.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const n = sync();
  console.log(
    `site content: ${n.decisions} decisions, ${n.research} research notes, tokens (${relative(ROOT, join(SITE, "src/styles/generated/tokens.css"))})`,
  );
}
