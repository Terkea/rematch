#!/usr/bin/env node
// Build-time content for the site (run before `astro dev`, `astro build` and `astro sync`):
// - the design tokens, from packages/ui/src/styles/tokens.css (DESIGN.md is the law), turned from a
//   Tailwind @theme block into plain custom properties;
// - the decision log, one page per docs/decisions/*.md plus an index from its README;
// - the research notes, one page per docs/research/*.md plus an index;
// - the roadmap, from GitHub's milestones and epics with `--roadmap-live` (the production build),
//   else from the seed files in .github/settings (roadmap-data.mjs, ADR 0099);
// - the "How it works" page, from the README's marked section, so the two never drift, and the
//   landing page's summary of it (the overview and each stage's title and first sentence).
// - the Experiments pages (lab/experiments/EXP-*/summary.md), the Progress page (docs/progress.md)
//   and the landing page's "Latest from the lab" strip.
// Everything written here is git-ignored and regenerated on every build.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadSeed } from "../../scripts/roadmap/roadmap-lib.mjs";
import {
  BASE,
  GITHUB_BLOB,
  howItWorksPage,
  howItWorksSummary,
  rewriteMarkdown,
  slugOf,
  titleOf,
} from "./content-lib.mjs";
import {
  experimentPage,
  experimentsIndex,
  labStrip,
  loadExperiments,
  loadLeaderboard,
  parseProgress,
  progressPage,
} from "./lab-lib.mjs";
import { loadRoadmap, writeRoadmap } from "./roadmap-data.mjs";

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(SITE, "..");
const OUT_DOCS = join(SITE, "src", "content", "docs", "docs");

// ---- tokens ---------------------------------------------------------------
export function tokensToPlainCss(css) {
  return (
    "/* Generated by site/scripts/sync-content.mjs from packages/ui/src/styles/tokens.css. Do not edit. */\n" +
    css
      .replace(/^@custom-variant[^\n]*\n/m, "")
      .replace(/@theme static \{/, ":root {")
      .replace(/^\s*--[a-z-]+-\*: initial;\n/gm, "")
  );
}

function writeTokens() {
  const src = readFileSync(join(ROOT, "packages", "ui", "src", "styles", "tokens.css"), "utf8");
  const dir = join(SITE, "src", "styles", "generated");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "tokens.css"), tokensToPlainCss(src));
}

// ---- markdown collections ---------------------------------------------------
function frontmatter(fields) {
  const lines = Object.entries(fields)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `${k}: ${typeof v === "string" ? JSON.stringify(v) : JSON.stringify(v)}`);
  return `---\n${lines.join("\n")}\n---\n\n`;
}

/** Collects `docs/<dir>/*.md` into `<out>/<slug>.md`; the README (if any) becomes the index. */
function syncCollection({ dir, route, indexTitle, indexIntro, order }) {
  const srcDir = join(ROOT, "docs", dir);
  const outDir = join(OUT_DOCS, route);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const files = readdirSync(srcDir)
    .filter((f) => f.endsWith(".md"))
    .sort();
  const pages = [];
  for (const file of files) {
    const raw = readFileSync(join(srcDir, file), "utf8");
    const repoPath = posix.join("docs", dir, file);
    const body = rewriteMarkdown(raw, repoPath);
    if (file === "README.md") continue;
    const title = titleOf(raw) ?? file.replace(/\.md$/, "");
    const slug = slugOf(file);
    pages.push({ file, slug, title });
    const withoutH1 = body.replace(/^# [^\n]*\n+/, "");
    writeFileSync(
      join(outDir, `${slug}.md`),
      frontmatter({
        title,
        editUrl: `${GITHUB_BLOB.replace("/blob/", "/edit/")}/${repoPath}`,
        sidebar: order ? { order: order(file) } : undefined,
      }) +
        `> Source: [\`${repoPath}\`](${GITHUB_BLOB}/${repoPath}). Generated at build time; edit the source file.\n\n` +
        withoutH1,
    );
  }
  let index;
  const readme = files.includes("README.md")
    ? readFileSync(join(srcDir, "README.md"), "utf8")
    : null;
  if (readme) {
    index = rewriteMarkdown(readme, posix.join("docs", dir, "README.md")).replace(
      /^# [^\n]*\n+/,
      "",
    );
  } else {
    index = pages.map((p) => `- [${p.title}](${BASE}/docs/${route}/${p.slug}/)`).join("\n");
  }
  writeFileSync(
    join(outDir, "index.md"),
    frontmatter({ title: indexTitle, sidebar: { order: 0, label: "Index" } }) +
      `${indexIntro}\n\n${index}\n`,
  );
  return pages;
}

// ---- how it works ---------------------------------------------------------
function writeHowItWorks() {
  const readme = readFileSync(join(ROOT, "README.md"), "utf8");
  const diagram = readFileSync(
    join(SITE, "src", "components", "how-it-works-diagram.html"),
    "utf8",
  );
  writeFileSync(
    join(OUT_DOCS, "how-it-works.md"),
    frontmatter({
      title: "How it works",
      description:
        "Every stage of Rematch with its real constants: import, Stockfish 19, enrichment, Syzygy, Maia-2, the weakness detectors, the statistics, peers, the coach and its validator, the trainer and the focus.",
      editUrl: `${GITHUB_BLOB.replace("/blob/", "/edit/")}/README.md`,
      sidebar: { order: 0 },
      // The stage disclosures hold h3s; the contents list keeps to the page's two h2 sections.
      tableOfContents: { maxHeadingLevel: 2 },
    }) +
      howItWorksPage(readme, diagram) +
      `\n<p class="generated-source">Generated at build time from the "How it works" section of <a href="${GITHUB_BLOB}/README.md#how-it-works">README.md</a>; edit it there.</p>\n`,
  );
}

/** The landing page's "How it works" (src/data/generated/how-it-works.json), from the README. */
function writeHowItWorksSummary() {
  const readme = readFileSync(join(ROOT, "README.md"), "utf8");
  const dir = join(SITE, "src", "data", "generated");
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "how-it-works.json"),
    `${JSON.stringify(howItWorksSummary(readme), null, 2)}
`,
  );
}

/** The champion: the algorithm version on this commit's manifest (ADR 0108). */
function championId() {
  return JSON.parse(readFileSync(join(ROOT, "algorithm", "manifest.json"), "utf8")).id;
}

/** The Experiments pages and the Progress page, plus the landing strip (src/data/generated/lab.json). */
function writeLab() {
  const exps = loadExperiments(join(ROOT, "lab"));
  const outDir = join(OUT_DOCS, "experiments");
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const edit = `${GITHUB_BLOB.replace("/blob/", "/edit/")}`;
  for (const e of exps) {
    writeFileSync(
      join(outDir, `${e.slug}.md`),
      frontmatter({
        title: `${e.id}: ${e.title}`,
        description: e.title,
        editUrl: `${edit}/lab/experiments/${e.folder}/summary.md`,
      }) + experimentPage(e),
    );
  }
  writeFileSync(
    join(outDir, "index.md"),
    frontmatter({
      title: "Experiments",
      description: "Every pre-registered experiment on the Rematch algorithm, with its status.",
      editUrl: `${edit}/lab/experiments/README.md`,
      sidebar: { order: 0, label: "Index" },
      tableOfContents: false,
    }) + experimentsIndex(exps, loadLeaderboard(join(ROOT, "lab")), championId()),
  );
  const progress = readFileSync(join(ROOT, "docs", "progress.md"), "utf8");
  writeFileSync(
    join(OUT_DOCS, "progress.md"),
    frontmatter({
      title: "Progress",
      description: "The milestones that moved Rematch, newest first.",
      editUrl: `${edit}/docs/progress.md`,
    }) + progressPage(progress),
  );
  const dir = join(SITE, "src", "data", "generated");
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "lab.json"),
    `${JSON.stringify(labStrip(exps, parseProgress(progress)), null, 2)}
`,
  );
  return exps.length;
}

export function sync() {
  writeTokens();
  const experiments = writeLab();
  writeHowItWorksSummary();
  writeHowItWorks();
  const decisions = syncCollection({
    dir: "decisions",
    route: "decisions",
    indexTitle: "Decision log",
    indexIntro:
      "Every decision in Rematch is written down as an architecture decision record (ADR): the context, the decision, the alternatives and the consequences. This log is generated at build time from [`docs/decisions/`](" +
      GITHUB_BLOB.replace("/blob/", "/tree/") +
      "/docs/decisions), so it is always the repository's own record. New decisions take the next number.",
    order: (f) => {
      const n = /^(\d{4})/.exec(f);
      return n ? Number(n[1]) : 10000;
    },
  });
  const research = syncCollection({
    dir: "research",
    route: "research",
    indexTitle: "Research notes",
    indexIntro:
      "The evidence behind the product: what helps amateur players improve, how competitors work, the legal ground and the technical facts the engine relies on. Generated at build time from [`docs/research/`](" +
      GITHUB_BLOB.replace("/blob/", "/tree/") +
      "/docs/research).",
  });
  return { decisions: decisions.length, research: research.length, experiments };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const n = sync();
  console.log(
    `site content: ${n.decisions} decisions, ${n.research} research notes, ${n.experiments} experiments, tokens (${relative(ROOT, join(SITE, "src/styles/generated/tokens.css"))})`,
  );
  const live = process.argv.includes("--roadmap-live") && process.env.ROADMAP_OFFLINE !== "1";
  const { model, note } = await loadRoadmap(loadSeed(ROOT), {
    live,
    token: process.env.GITHUB_TOKEN,
  });
  writeRoadmap(join(SITE, "src", "data", "generated", "roadmap.json"), model);
  console.log(`site roadmap: ${model.milestones.length} milestones from ${note}`);
}
