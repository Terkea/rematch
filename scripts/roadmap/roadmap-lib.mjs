// The roadmap model the README summary and the site's roadmap page share (ADR 0099). GitHub's
// milestones and issues are the source of truth; .github/settings/milestones.json and
// roadmap-issues.json are the seed and the fallback when the API cannot be read (the repository
// is private, the build is offline, or the rate limit is spent). No dependencies.
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const REPO = "Terkea/rematch";
export const REPO_URL = `https://github.com/${REPO}`;
export const MILESTONES_URL = `${REPO_URL}/milestones`;
export const HORIZON_TITLES = { now: "Now", next: "Next", later: "Later" };

export const README_START =
  "<!-- roadmap:start (generated by scripts/roadmap/render-readme.mjs; edit .github/settings/milestones.json and roadmap-issues.json) -->";
export const README_END = "<!-- roadmap:end -->";

/** The issues of one milestone, as a search link that works before the milestone has a number. */
export function milestoneSearchUrl(title) {
  const q = `is:issue milestone:"${title}"`;
  return `${REPO_URL}/issues?q=${encodeURIComponent(q).replaceAll("%20", "+")}`;
}

export function loadSeed(root) {
  const read = (p) => JSON.parse(readFileSync(join(root, ".github", "settings", p), "utf8"));
  return { milestones: read("milestones.json"), issues: read("roadmap-issues.json") };
}

/**
 * The model from the seed files alone: every milestone open, nothing done. `issues` counts the
 * seed issues per milestone; each epic lists its seeded sub-issues.
 */
export function fromSeed(seed) {
  return {
    source: "seed",
    milestones: seed.milestones.map((m) => {
      const mine = seed.issues.filter((i) => i.milestone === m.title);
      return {
        title: m.title,
        description: m.description,
        horizon: m.horizon,
        state: m.state,
        url: milestoneSearchUrl(m.title),
        closed: null,
        total: mine.length,
        epics: mine
          .filter((i) => i.epic)
          .map((e) => ({
            title: e.title,
            url: null,
            state: "open",
            done: null,
            total: seed.issues.filter((i) => i.parent === e.title).length,
          })),
      };
    }),
  };
}

/**
 * The model from the GitHub API: `apiMilestones` from `GET /repos/{repo}/milestones?state=all`,
 * `apiEpics` from `GET /repos/{repo}/issues?labels=epic&state=all` (each with
 * `sub_issues_summary`). The horizon comes from the seed; a milestone the seed does not know is
 * Later. Closed milestones are left out: they are shipped, and the changelog lists them.
 */
export function fromGitHub(seed, apiMilestones, apiEpics) {
  const horizon = new Map(seed.milestones.map((m) => [m.title, m.horizon]));
  const order = new Map(seed.milestones.map((m, i) => [m.title, i]));
  const rank = (t) => order.get(t) ?? Number.MAX_SAFE_INTEGER;
  return {
    source: "github",
    milestones: apiMilestones
      .filter((m) => m.state === "open")
      .sort((a, b) => rank(a.title) - rank(b.title) || a.title.localeCompare(b.title))
      .map((m) => ({
        title: m.title,
        description: m.description ?? "",
        horizon: horizon.get(m.title) ?? "later",
        state: m.state,
        url: m.html_url,
        closed: m.closed_issues,
        total: m.open_issues + m.closed_issues,
        epics: apiEpics
          .filter((e) => !e.pull_request && e.milestone?.number === m.number)
          .sort((a, b) => a.number - b.number)
          .map((e) => ({
            title: e.title,
            url: e.html_url,
            state: e.state,
            done: e.sub_issues_summary?.completed ?? 0,
            total: e.sub_issues_summary?.total ?? 0,
          })),
      })),
  };
}

/** "3 of 7 done", or "7 issues" when progress is unknown (the seed). */
export function progressText(done, total, noun = "issue") {
  if (done === null || done === undefined) return `${total} ${noun}${total === 1 ? "" : "s"}`;
  return `${done} of ${total} done`;
}

const stripEpic = (t) => {
  const name = t.replace(/^Epic: /, "");
  return name.charAt(0).toUpperCase() + name.slice(1);
};

/**
 * The README's roadmap block, from the seed files only, so it is deterministic and CI can check
 * it is current. Live progress is one click away on the milestones page.
 */
export function renderReadmeBlock(seed) {
  const model = fromSeed(seed);
  const lines = [README_START, ""];
  for (const h of Object.keys(HORIZON_TITLES)) {
    const ms = model.milestones.filter((m) => m.horizon === h && m.state === "open");
    if (ms.length === 0) continue;
    lines.push(`### ${HORIZON_TITLES[h]}`, "");
    for (const m of ms) {
      lines.push(`- [${m.title}](${m.url})`);
      for (const e of m.epics) {
        lines.push(`  - ${stripEpic(e.title)} (${progressText(null, e.total, "sub-issue")})`);
      }
    }
    lines.push("");
  }
  lines.push(
    `Live progress (done of total) is on the [milestones page](${MILESTONES_URL}) and the [site's roadmap](https://terkea.github.io/rematch/docs/roadmap/).`,
    "",
    README_END,
  );
  return lines.join("\n");
}

/** `text` with the block between the markers replaced; throws when the markers are missing. */
export function replaceBlock(text, block) {
  const start = text.indexOf("<!-- roadmap:start");
  const end = text.indexOf(README_END);
  if (start < 0 || end < start) {
    throw new Error(`README.md needs the roadmap markers: ${README_START} ... ${README_END}`);
  }
  return text.slice(0, start) + block + text.slice(end + README_END.length);
}
