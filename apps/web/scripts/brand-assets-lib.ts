import { brand } from "../src/brand";

// The pure half of `scripts/brand-assets.ts`: text transforms of the committed logo SVGs in
// packages/ui/assets/brand, and the ICO container. The rasters come from the system Chrome.

/** Ink, by day (the spec's `--color-ink`). The logo is ink only, never pen red. */
export const BRAND_INK = "#1F2A3D";
/** Ink at night (the spec's night cream), for dark browser chrome. */
export const BRAND_NIGHT_INK = "#E8E2D6";
/** Pencil, the warm graphite of secondary text on the social card. */
export const BRAND_PENCIL = "#6B6458";
/** The paper behind the raster icons, where a platform needs an opaque tile. */
export const BRAND_PAPER = "#F4EFE6";

/** The SVG's viewBox and its inner markup, without the `<title>`. */
export function svgParts(source: string): { viewBox: string; body: string } {
  const viewBox = source.match(/viewBox="([^"]+)"/)?.[1];
  const body = source.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!viewBox || body === undefined) throw new Error("brand: not an SVG");
  return { viewBox, body: body.replace(/<title>[\s\S]*?<\/title>/, "").trim() };
}

/** Prefix every `id` and its `url(#…)` references, so two inline copies can't collide. */
export function scopeIds(body: string, prefix: string): string {
  return body
    .replace(/id="([^"]+)"/g, `id="${prefix}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${prefix}-$1)`);
}

/** The browser-tab icon: the icon in ink, and in night cream when the browser chrome is dark. */
export function iconSvg(source: string): string {
  const { viewBox, body } = svgParts(source);
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">`,
    `<title>${brand.name}</title>`,
    `<style>svg{color:${BRAND_INK}}@media (prefers-color-scheme: dark){svg{color:${BRAND_NIGHT_INK}}}</style>`,
    body,
    "</svg>",
    "",
  ].join("\n");
}

/** The mark in one fixed colour, for an `<img>` (GitHub's README), where currentColor is black. */
export function solidSvg(source: string, colour: string, title: string): string {
  const { viewBox, body } = svgParts(source);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img"><title>${title}</title>${body.replaceAll("currentColor", colour)}</svg>\n`;
}

/** The TypeScript module that inlines the icon into the app's lockup. */
/**
 * The icon's knock-out mask (a full square less the board's corner) as the same even-odd clip,
 * so the inlined copy carries no colour of its own, only currentColor.
 */
export function maskToClip(body: string): string {
  const out = body
    .replace(
      /<mask id="([^"]+)"><path fill="#fff" d="([^"]+)"\/><path d="([^"]+)"\/><\/mask>/g,
      '<clipPath id="$1"><path clip-rule="evenodd" d="$2 $3"/></clipPath>',
    )
    .replace(/mask="url\(#([^)]+)\)"/g, 'clip-path="url(#$1)"');
  if (/<mask|#[0-9a-f]{3,6}\b/i.test(out)) throw new Error("brand: the icon has a colour left");
  return out;
}

export function iconModule(source: string): string {
  const { viewBox, body: raw } = svgParts(source);
  const body = maskToClip(raw);
  return `// Generated by scripts/brand-assets.ts from packages/ui/assets/brand/rematch-icon.svg.
// Do not edit by hand: run \`pnpm --filter @ci/web brand\`.
export const REMATCH_ICON = {
  viewBox: ${JSON.stringify(viewBox)},
  body: ${JSON.stringify(scopeIds(body, "rematch-icon"))},
} as const;
`;
}

/** An ICO file holding one PNG per size (Vista and later read PNG entries). */
export function icoFile(images: { size: number; png: Buffer }[]): Buffer {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, png }, i) => {
    const at = 6 + i * 16;
    header.writeUInt8(size >= 256 ? 0 : size, at);
    header.writeUInt8(size >= 256 ? 0 : size, at + 1);
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(png.length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += png.length;
  });
  return Buffer.concat([header, ...images.map((i) => i.png)]);
}
